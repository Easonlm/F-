def top_section(title: str) -> str:
    pattern = rf"(?ms)^## {re.escape(title)}\n(.*?)(?=^## |\Z)"
    match = re.search(pattern, src)
    if not match:
        raise KeyError(title)
    return match.group(1).strip()


def subparts(title: str) -> tuple[str, dict[str, str]]:
    body = top_section(title)
    hits = list(re.finditer(r"(?m)^### (.+)$", body))
    intro = body[: hits[0].start()].strip() if hits else body
    parts = {}
    for i, hit in enumerate(hits):
        end = hits[i + 1].start() if i + 1 < len(hits) else len(body)
        parts[hit.group(1).strip()] = body[hit.end():end].strip()
    return intro, parts


def without_figures(value: str) -> str:
    return re.sub(r"(?m)^!\[[^\n]*\]\([^\n]+\)\s*$", "", value).strip()


def demote(value: str) -> str:
    return re.sub(r"(?m)^### ", "#### ", value)


def part(section: str, heading: str, new_heading: str, keep_figures: bool = False) -> str:
    _, sections = subparts(section)
    body = sections[heading]
    if not keep_figures:
        body = without_figures(body)
    return f"### {new_heading}\n\n{body}"


def table_from_csv(path: str, columns: list[str], labels: list[str], max_rows: int | None = None,
                   where: dict[str, str] | None = None) -> str:
    with (ROOT / path).open(encoding="utf-8-sig", newline="") as stream:
        rows = list(csv.DictReader(stream))
    if where:
        rows = [row for row in rows if all(row.get(k) == v for k, v in where.items())]
    if max_rows is not None:
        rows = rows[:max_rows]
    out = ["| " + " | ".join(labels) + " |", "|" + "|".join(["---"] * len(labels)) + "|"]
    for row in rows:
        cells = []
        for column in columns:
            cell = str(row.get(column, "")).replace("|", "/").replace("\n", " ")
            if re.fullmatch(r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?", cell) and len(cell) > 10:
                cell = f"{float(cell):.6g}"
            cells.append(cell)
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


